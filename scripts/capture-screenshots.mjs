import { chromium } from "@playwright/test"
import sharp from "sharp"
import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"

const captured = "30 October 2026"
const enterDemo = async (page) => {
  const demo = page.getByText("Try the live demo", { exact: false }).first()
  if (await demo.count()) {
    await demo.click({ timeout: 5_000 })
    await page.waitForTimeout(2_500)
  }
}

const sites = [
  { slug: "sa-jas", url: "https://sajas.pages.dev/", prepare: enterDemo },
  { slug: "clearcut", url: "https://145-241-100-85.sslip.io/", prepare: enterDemo },
  { slug: "munisolve", url: "https://munisolve-za.vercel.app" },
  { slug: "reservoir", url: "https://konethegreat.github.io/reservoir/" },
  { slug: "ui-vault", url: "https://konethegreat.github.io/ui-vault/" },
  { slug: "k-one", url: "https://k-one-it-solutions-website.erictshivhinda.workers.dev/" },
  { slug: "timelex", url: "https://timelex-automated-time-tracking.netlify.app/" },
]
const viewports = {
  desktop: { width: 1440, height: 900 },
  phone: { width: 390, height: 844 },
}

const browser = await chromium.launch()
const results = {}

for (const site of sites) {
  const entry = {}
  for (const [name, viewport] of Object.entries(viewports)) {
    const context = await browser.newContext({ viewport, deviceScaleFactor: 1 })
    const page = await context.newPage()
    try {
      const response = await page.goto(site.url, { waitUntil: "load", timeout: 45_000 })
      if (!response || response.status() >= 400) throw new Error(`HTTP ${response?.status()}`)
      await page.waitForTimeout(2500)
      if (site.prepare) {
        try {
          await site.prepare(page)
        } catch (error) {
          console.warn(`prepare ${site.slug} ${name}: ${error.message}`)
        }
      }
      const png = await page.screenshot({ type: "png" })
      const dir = path.join("public", "shots", site.slug)
      await mkdir(dir, { recursive: true })
      const file = path.join(dir, `${name}.webp`)
      await sharp(png).webp({ quality: 82 }).toFile(file)
      entry[name] = {
        src: `/shots/${site.slug}/${name}.webp`,
        width: viewport.width,
        height: viewport.height,
        captured,
        source: site.url,
      }
      console.log(`captured ${site.slug} ${name}`)
    } catch (error) {
      console.warn(`skipped ${site.slug} ${name}: ${error.message}`)
    } finally {
      await context.close()
    }
  }
  if (entry.desktop) results[site.slug] = entry
}

await browser.close()
const header =
  "// AUTO-GENERATED by scripts/capture-screenshots.mjs. Do not edit by hand.\n" +
  "export interface SiteShot {\n  src: string\n  width: number\n  height: number\n  captured: string\n  source: string\n}\n\n" +
  "export const siteShots: Record<string, { desktop: SiteShot; phone: SiteShot }> = "
await writeFile("src/data/shots.generated.ts", header + JSON.stringify(results, null, 2) + "\n")
console.log(`wrote ${Object.keys(results).length} sites`)
