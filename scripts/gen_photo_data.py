"""Turn public/images/_photos.json into src/data/photos.generated.ts"""
import json, sys
src = json.load(open("public/images/_photos.json"))
out = ["// AUTO-GENERATED by scripts/gen_photo_data.py — do not edit by hand.\n",
       "export interface PhotoSource { file: string; w: number; h: number }\n",
       "export interface Photo { slug: string; w: number; h: number; ratio: number; lqip: string; sources: PhotoSource[] }\n\n",
       "export const photos: Record<string, Photo> = {\n"]
for key, m in src.items():
    srcs = ", ".join('{ file: "%s", w: %d, h: %d }' % (f["file"], f["w"], f["h"]) for f in m["files"])
    out.append('  "%s": { slug: "%s", w: %d, h: %d, ratio: %s, lqip: "%s", sources: [%s] },\n' % (key, m["slug"], m["w"], m["h"], m["ratio"], m["lqip"], srcs))
out.append("}\n")
open("src/data/photos.generated.ts", "w").write("".join(out))
print("ok", len(src))
